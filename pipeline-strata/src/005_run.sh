#!/bin/bash
#SBATCH --job-name=gwas
#SBATCH --output=src/logs/%x.log
#SBATCH --error=src/logs/%x.err
#SBATCH --time=10-00:00:00
#SBATCH --mem=32G
#SBATCH --cpus-per-task=2
#SBATCH --partition=low_p
#SBATCH --open-mode=truncate

# Script: src/005_run.sh  (pipeline-strata)
# Purpose: SLURM submission for the STRATIFIED extended analysis.
#
# Which strata run is decided in two places, both outside this script:
#   pipeline/params.yaml   defines the strata (column + accepted values)
#   pipeline/samplesheet.csv  lists, per study, the strata large enough to run
#                             (written by src/003_data-phenotype.R)
# Edit the SBATCH header above to change job name, logs, or cluster resources.
#
# Partitions:
#   - This #SBATCH --partition line sets the partition for the LAUNCHER job only
#     (the lightweight Nextflow driver). Override per-submit without editing:
#         sbatch --partition=low_p src/005_run.sh
#   - The partition for ALL submitted pipeline tasks (REGENIE, etc.) is the single
#     global knob GWAS_PARTITION in .env (read by pipeline/nextflow.config).

set -euo pipefail

SCRIPT_SOURCE="${BASH_SOURCE[0]:-$0}"
SCRIPT_DIR="$(cd "$(dirname -- "$SCRIPT_SOURCE")" && pwd)"
if [[ -n "${SLURM_SUBMIT_DIR:-}" ]]; then
  DEFAULT_PROJ_ROOT="${SLURM_SUBMIT_DIR}"
else
  DEFAULT_PROJ_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
fi

# Shared .env loader (src/lib/env.sh): an exported variable always beats .env.
_gwas_find_lib() {
  local c
  for c in "${SLURM_SUBMIT_DIR:-/nonexistent}/src/lib/env.sh" \
           "${DEFAULT_PROJ_ROOT:-/nonexistent}/src/lib/env.sh" \
           "${SCRIPT_DIR:-/nonexistent}/lib/env.sh" \
           "${SCRIPT_DIR:-/nonexistent}/../lib/env.sh" \
           "$(dirname -- "${BASH_SOURCE[0]:-$0}")/lib/env.sh" \
           "$(dirname -- "${BASH_SOURCE[0]:-$0}")/../lib/env.sh"; do
    if [[ -f "$c" ]]; then printf '%s
' "$c"; return 0; fi
  done
  return 1
}
_GWAS_ENV_LIB="$(_gwas_find_lib)" || {
  echo "ERROR: src/lib/env.sh not found. The tree is incompletely synced;" >&2
  echo "       rsync pipeline-strata/ again (see TRANSFER.md)." >&2
  exit 1
}
# shellcheck disable=SC1090
source "$_GWAS_ENV_LIB"

resolve_path() {
  local path="$1"
  case "$path" in
    /*) printf '%s\n' "$path" ;;
    *) printf '%s\n' "${PROJ_ROOT%/}/$path" ;;
  esac
}

source_env_file "${DEFAULT_PROJ_ROOT}/.env"
PROJ_ROOT="${GWAS_PROJECT_ROOT:-$DEFAULT_PROJ_ROOT}"
PIPELINE_DIR="${PROJ_ROOT}/pipeline"
PARAMS_FILE="${PIPELINE_DIR}/params.yaml"

PROFILE="slurm"
BATCH_ARG=""
RESULT_DIR="${GWAS_RESULTS_DIR:-/WHERE/epic-gwas/results}"
# Phenotype files live alongside the genetics data, under <data>/phenotype/,
# where <data> is the parent of GWAS_GENETICS_DIR (same as 003/004).
GENETICS_DIR="${GWAS_GENETICS_DIR:-data/genetics}"
# Honour GWAS_PHENO_DIR. The derived fallback resolves to the FROZEN tree's
# data/phenotype -- an input to the published analysis -- because both trees
# share GWAS_GENETICS_DIR.
PHENO_DIR="${GWAS_PHENO_DIR:-$(dirname "$GENETICS_DIR")/phenotype}"
INCLUDE_STUDIES=""
INCLUDE_PROTEINS="${GWAS_INCLUDE_PROTEINS:-${PHENO_DIR}/test.txt}"
PHENO_FILE="${GWAS_PHENO_FILE:-${PHENO_DIR}/phenofile.txt}"
# Samplesheet generated by 004 (on scratch); overrides the params.yaml default.
SAMPLESHEET="${GWAS_SAMPLESHEET:-${PROJ_ROOT}/pipeline/samplesheet.csv}"
COVAR_FILE=""
# PHENO (disease status) is resolved from the study .psam by
# prepare_covariates.py. In the frozen tree it was reachable only while it was
# also the grouping variable; here the grouping variable is smoking/BMI, so it
# has to be requested explicitly.
COVARIATES="Sex,Age_Recr,PHENO"
# Deliberately EMPTY. Anything set here is passed on the Nextflow command line,
# and CLI params OVERRIDE -params-file -- so a default here silently shadows
# pipeline/params.yaml. That is what dropped the third meta group: params.yaml
# said "ever,never,meta" and this wrapper quietly overrode it with "ever,never".
# These are now only passed when given explicitly on this script's command line.
META_GROUP=""
META_STUDY=""
META_GROUP_SET=0
META_STUDY_SET=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --batch)
      BATCH_ARG="$2"
      shift 2
      ;;
    --profile)
      PROFILE="$2"
      shift 2
      ;;
    --out|-o|--outdir)
      RESULT_DIR="$2"
      shift 2
      ;;
    --studies)
      INCLUDE_STUDIES="$2"
      shift 2
      ;;
    --proteins)
      INCLUDE_PROTEINS="$2"
      shift 2
      ;;
    --pheno)
      PHENO_FILE="$2"
      shift 2
      ;;
    --covar)
      COVAR_FILE="$2"
      shift 2
      ;;
    --samplesheet)
      SAMPLESHEET="$2"
      shift 2
      ;;
    --covariates)
      COVARIATES="$2"
      shift 2
      ;;
    --meta-group)
      META_GROUP="$2"
      META_GROUP_SET=1
      shift 2
      ;;
    --meta-study)
      META_STUDY="$2"
      META_STUDY_SET=1
      shift 2
      ;;
    -h|--help)
      cat <<'EOF'
Usage:
  sbatch src/005_run.sh [options]

Options:
  --batch       Path to a batch file without .txt extension. Sets the protein
                list to <path>.txt. Output directory is set by GWAS_RESULTS_DIR
                in .env (or --out to override). Example: --batch data/phenotype/batch1
  --profile     Nextflow profile (default: slurm)
  --out, -o     Output directory for results (default: GWAS_ANALYSIS_DIR)
  --studies     Comma-separated list of studies (default: all in samplesheet)
  --proteins    Comma-separated list of proteins or a file path
  --pheno       Path to phenotype file (default: <data>/phenotype/phenofile.txt)
  --covar       Path to covariate file
  --samplesheet Path to the samplesheet (default: GWAS_SAMPLESHEET)
  --covariates  Comma-separated covariate names (default: Sex,Age_Recr)
  --meta-group  within-study meta across a PAIR of strata, e.g. "ever,never";
                empty to disable (default: disabled). Rarely wanted -- pooling
                ever+never just reconstructs the unstratified analysis.
  --meta-study  strata to meta-analyse across studies, each independently,
                e.g. "all,ever,never" (default: all,ever,never)

SLURM settings such as job name, logs, time, memory, CPUs, and partition are
defined in the #SBATCH header at the top of src/005_run.sh.
EOF
      exit 0
      ;;
    *)
      echo "Unknown argument: $1" >&2
      exit 1
      ;;
  esac
done

if [[ -n "$BATCH_ARG" ]]; then
  BATCH_PATH="$(resolve_path "$BATCH_ARG")"
  BATCH_NAME="$(basename -- "$BATCH_PATH")"
  INCLUDE_PROTEINS="${BATCH_PATH}.txt"
fi

if [[ ! -d "$PIPELINE_DIR" ]]; then
  echo "ERROR: Pipeline directory not found: $PIPELINE_DIR" >&2
  exit 1
fi

ABS_RESULT_DIR="$(resolve_path "$RESULT_DIR")"
mkdir -p "$ABS_RESULT_DIR"
mkdir -p "${PROJ_ROOT}/src/logs"

ABS_SAMPLESHEET="$(resolve_path "$SAMPLESHEET")"
if [[ ! -f "$ABS_SAMPLESHEET" ]]; then
  echo "ERROR: Samplesheet not found: $ABS_SAMPLESHEET" >&2
  echo "       Generate it first with: Rscript src/003_data-phenotype.R" >&2
  exit 1
fi

if [[ -n "$PHENO_FILE" ]]; then
  ABS_PHENO="$(resolve_path "$PHENO_FILE")"
  if [[ ! -f "$ABS_PHENO" ]]; then
    echo "ERROR: Phenotype file not found: $ABS_PHENO" >&2
    exit 1
  fi
else
  ABS_PHENO=""
fi

if [[ -n "$COVAR_FILE" ]]; then
  ABS_COVAR="$(resolve_path "$COVAR_FILE")"
  if [[ ! -f "$ABS_COVAR" ]]; then
    echo "ERROR: Covariate file not found: $ABS_COVAR" >&2
    exit 1
  fi
else
  ABS_COVAR=""
fi

ABS_PROTS=""
if [[ -n "$INCLUDE_PROTEINS" ]]; then
  PROTEIN_PATH_CANDIDATE="$(resolve_path "$INCLUDE_PROTEINS")"
  if [[ -f "$PROTEIN_PATH_CANDIDATE" ]]; then
    ABS_PROTS="$PROTEIN_PATH_CANDIDATE"
  fi
fi

# A samplesheet built against a different genetics directory is the single
# failure that has cost the most time here: the paths still resolve, the files
# exist, and the run dies 27 tasks later on a missing PHENO column. Check the
# samplesheet agrees with the genetics directory this .env names, before
# anything is submitted.
if [[ -n "${GWAS_GENETICS_DIR:-}" && -f "$ABS_SAMPLESHEET" ]]; then
  SS_BAD="$(awk -F, -v want="${GWAS_GENETICS_DIR%/}" '
    NR==1 { for (i=1;i<=NF;i++) if ($i=="sample_file") c=i; next }
    c && $c !~ "^"want"/" { print $1 }' "$ABS_SAMPLESHEET" | head -5)"
  if [[ -n "$SS_BAD" ]]; then
    echo "ERROR: samplesheet does not match GWAS_GENETICS_DIR." >&2
    echo "  GWAS_GENETICS_DIR : ${GWAS_GENETICS_DIR}" >&2
    echo "  samplesheet       : ${ABS_SAMPLESHEET}" >&2
    echo "  studies pointing elsewhere: $(echo "$SS_BAD" | tr '\n' ' ')" >&2
    echo "  The samplesheet is stale. Rebuild it:  sbatch src/003_data-phenotype.sh" >&2
    exit 1
  fi
fi

if ! command -v conda >/dev/null 2>&1; then
  echo "ERROR: conda is required to launch the GWAS pipeline." >&2
  exit 1
fi

source "$(conda info --base)/etc/profile.d/conda.sh"
conda activate nf_master
unset R_HOME

export GWAS_PROJECT_ROOT="$PROJ_ROOT"
export NXF_OPTS="${NXF_OPTS:- -Xms4g -Xmx24g}"
# Keep Nextflow's own log out of the project root (route into src/logs/).
export NXF_LOG_FILE="${NXF_LOG_FILE:-${PROJ_ROOT}/src/logs/nextflow.log}"
# Work directory on scratch (consumed by the slurm profile in nextflow.config).
export GWAS_WORK_DIR="${GWAS_WORK_DIR:-/WHERE/epic-gwas/work-strata}"
if [[ "${GWAS_WORK_DIR}" == "/WHERE/epic-gwas/work" ]]; then
  echo "ERROR: GWAS_WORK_DIR is the frozen publication tree's work directory." >&2
  echo "       Set it to a separate path in .env (e.g. .../work-strata)." >&2
  exit 1
fi
# Per-run cache directory so concurrent batch submissions don't share a lock.
export NXF_CACHE_DIR="${ABS_RESULT_DIR}/.nf-cache"

echo "=========================================="
echo " Launching Nextflow GWAS Pipeline"
echo "=========================================="
echo "Pipeline: $PIPELINE_DIR"
echo "Profile:  $PROFILE"
echo "Studies:  ${INCLUDE_STUDIES:-ALL}"
echo "Proteins: ${INCLUDE_PROTEINS:-ALL}${BATCH_ARG:+ (batch: $BATCH_NAME)}"
echo "Output:   $ABS_RESULT_DIR"
echo "Covars:   ${COVARIATES}"
echo "Meta-group: ${META_GROUP:-<from params.yaml>}"
echo "Meta-study: ${META_STUDY:-<from params.yaml>}"
echo "Partition (tasks): ${GWAS_PARTITION:-low_p}"
echo "=========================================="

NF_CMD=(
  nextflow run main.nf
  -profile "$PROFILE"
  -resume
  -params-file "$PARAMS_FILE"
  --samplesheet "$ABS_SAMPLESHEET"
  --outdir "$ABS_RESULT_DIR"
)

if [[ -n "$INCLUDE_STUDIES" ]]; then
  NF_CMD+=(--include_studies "$INCLUDE_STUDIES")
fi

if [[ -n "$INCLUDE_PROTEINS" ]]; then
  NF_CMD+=(--include_proteins "${ABS_PROTS:-$INCLUDE_PROTEINS}")
fi

if [[ -n "$ABS_PHENO" ]]; then
  NF_CMD+=(--phenotype_file "$ABS_PHENO")
fi

if [[ -n "$ABS_COVAR" ]]; then
  NF_CMD+=(--covariate_file "$ABS_COVAR")
fi

if [[ -n "$COVARIATES" ]]; then
  NF_CMD+=(--covariates "$COVARIATES")
fi

if [[ "$META_GROUP_SET" -eq 1 ]]; then
  NF_CMD+=(--meta_group "$META_GROUP")
fi


if [[ "$META_STUDY_SET" -eq 1 ]]; then
  NF_CMD+=(--meta_study "$META_STUDY")
fi

echo "Executing:"
printf 'cd %q &&' "$PIPELINE_DIR"
printf ' %q' "${NF_CMD[@]}"
echo

cd "$PIPELINE_DIR"
"${NF_CMD[@]}"
